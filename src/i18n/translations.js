export function translate(dict, key) {
  if (key == null || dict == null) return ''
  const parts = Array.isArray(key) ? key : String(key).split('.')
  const value = parts.reduce((acc, part) => (acc == null ? acc : acc[part]), dict)
  return typeof value === 'string' ? value : ''
}
